DO $$ BEGIN
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='juanca_app') THEN CREATE ROLE juanca_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE; END IF;
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='juanca_ingestion') THEN CREATE ROLE juanca_ingestion LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE; END IF;
 IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='juanca_market') THEN CREATE ROLE juanca_market LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE; END IF;
END $$;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION juanca_app;
CREATE SCHEMA IF NOT EXISTS ingestion AUTHORIZATION juanca_ingestion;
CREATE SCHEMA IF NOT EXISTS market AUTHORIZATION juanca_market;
REVOKE ALL ON SCHEMA app,ingestion,market FROM PUBLIC;
